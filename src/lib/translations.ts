export function getTranslation(lang?: string): TranslationKeys {
  const base = TRANSLATIONS.English as TranslationKeys;
  if (!lang) return base;
  const match = Object.keys(TRANSLATIONS).find(
    (key) => key.toLowerCase() === lang.toLowerCase()
  ) as SupportedLanguage | undefined;
  if (!match) return base;
  const selected = TRANSLATIONS[match];
  return { ...base, ...selected } as TranslationKeys;
}

export function getLocaleCode(lang?: string): string {
  if (!lang) return "en-US";
  const match = Object.keys(LANGUAGE_LOCALE_MAP).find(
    (key) => key.toLowerCase() === lang.toLowerCase()
  ) as SupportedLanguage | undefined;
  return match ? LANGUAGE_LOCALE_MAP[match] : "en-US";
}

export function formatNumberToLocale(text: string | number, localeCode: string): string {
  if (text === null || text === undefined) return "";
  const str = String(text);
  if (!str) return "";
  
  try {
    const formatter = new Intl.NumberFormat(localeCode, { useGrouping: false });
    const localizedDigits = Array.from({length: 10}, (_, i) => formatter.format(i));
    return str.replace(/[0-9]/g, (digit) => localizedDigits[parseInt(digit, 10)]);
  } catch (e) {
    return str;
  }
}

export function localizeDataString(dataStr: string | number, t: TranslationKeys, localeCode: string): string {
  let s = formatNumberToLocale(dataStr, localeCode);
  
  const replacements = [
    { from: "steps", to: t.unitSteps || "steps" },
    { from: "Restful", to: t.unitRestful || "Restful" },
    { from: "hrs", to: t.unitHrs || "hrs" },
    { from: "h ", to: (t.unitH || "h") + " " },
    { from: "m ", to: (t.unitM || "m") + " " },
    { from: "bpm", to: t.unitBpm || "bpm" },
    { from: "kcal", to: t.unitKcal || "kcal" },
    { from: "km", to: t.unitKm || "km" },
    { from: "1 tablet", to: t.oneTablet || "1 tablet" },
    { from: "N/A", to: t.notAvailable || "N/A" },
    { from: "Calm & Cheerful", to: t.calmAndCheerful || "Calm & Cheerful" }
  ];

  for (const rep of replacements) {
    s = s.replace(new RegExp(`\\b${rep.from}\\b`, 'g'), rep.to);
  }
  
  // also check for literal match without word boundaries for some strings like "h " 
  if (s.includes("h ")) s = s.replace("h ", (t.unitH || "h") + " ");
  if (s.includes("m ")) s = s.replace("m ", (t.unitM || "m") + " ");
  
  return s;
}
